// Builds the line table of the Madina mushaf: for every ayah, the line its first word is on and
// the line its last word is on (surah titles and basmalas included: they take room on the page).
// It lets a question say "one page" or "half a page" from any ayah. Lines are counted through the
// whole mushaf as printed: 15 a page, except pages 1 and 2 (Al-Fatiha and the start of Al-Baqara),
// which hold 8. Reads public/mushaf/pages/*.json and writes lib/quran/lines.ts here and
// src/lib/quranLines.ts in unis-be (the same content).
//   node scripts/build-ayah-lines.mjs
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const pageHeight = (page) => (page <= 2 ? 8 : 15);
const first = new Map(); // "s:a" → global line of its first word (0-based)
const last = new Map();
const pageOfAyah = new Map();
const order = [];

let pageTop = 0; // global line of the current page's line 1
for (let page = 1; page <= 604; page++) {
  const data = JSON.parse(readFileSync(join(root, "public/mushaf/pages", `${page}.json`), "utf8"));
  for (const [line, words] of data.lines) {
    if (line < 1 || line > pageHeight(page)) throw new Error(`Page ${page} has a line ${line}`);
    const at = pageTop + (line - 1);
    for (const [surah, ayah] of words) {
      const key = `${surah}:${ayah}`;
      if (!first.has(key)) {
        first.set(key, at);
        pageOfAyah.set(key, page);
        order.push(key);
      }
      // A question ends at the end of an ayah: in this mushaf every page ends with one. Checked, so
      // another print with an ayah running over a page break would be noticed here.
      if (pageOfAyah.get(key) !== page) throw new Error(`${key} runs from page ${pageOfAyah.get(key)} onto page ${page}`);
      last.set(key, at);
    }
  }
  pageTop += pageHeight(page);
}
if (order.length !== 6236) throw new Error(`Expected 6236 ayahs, found ${order.length}`);

// Two base-36 characters per ayah: how many lines after the previous ayah's first line it starts,
// then how many lines after its own first line it ends. Neither goes past 35 (checked).
let prev = 0;
let text = "";
for (const key of order) {
  const start = first.get(key);
  const step = start - prev;
  const span = last.get(key) - start;
  if (step < 0 || step > 35 || span > 35) throw new Error(`Out of range at ${key}: ${step} ${span}`);
  text += step.toString(36) + span.toString(36);
  prev = start;
}

const file = `// GENERATED by unis-fr/scripts/build-ayah-lines.mjs from the mushaf pages: do not edit by hand.
// For each ayah in order, 2 base-36 characters: lines from the previous ayah's first line to this
// one's, then lines from its first line to its last. Lines are counted through the mushaf as
// printed: 15 a page, pages 1 and 2 hold 8.
export const AYAH_LINES = "${text}";
`;
writeFileSync(join(root, "lib/quran/lines.ts"), file);
const be = join(root, "../unis-be/src/lib/quranLines.ts");
if (existsSync(dirname(be))) writeFileSync(be, file);
console.log(`${order.length} ayahs, ${text.length} characters`);
